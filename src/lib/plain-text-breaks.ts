/**
 * Разбор проверки задачи модель пишет «без markdown» (см. prompts.ts): шаги разделены одиночным
 * переводом строки. В markdown одиночный \n — мягкий перенос, и шаги сливаются в один абзац.
 * Превращаем одиночные переносы в жёсткие («два пробела + \n»); пустые строки (абзацы) не трогаем.
 */
export function softBreaksToHardBreaks(text: string): string {
  return text.replace(/\r\n?/g, "\n").replace(/([^\n])[ \t]*\n(?!\n)/g, "$1  \n");
}
